"""Write the job list for the main p=0.005 study (5 seeds, KD 0.5 recipe) to jobs/study.txt.

A  layer-0 saliency: n of 24 detectors expanded, method x k
B  hidden-layer expansion on top of a fully 3-bit layer 0
C  equal-cost Pareto: plain BNN widths vs layer-0-expanded BNN widths

  python host/make_study.py && python host/run_jobs.py jobs/study.txt --parallel 3
"""

from pathlib import Path

DATA = "data/d3_r3_p0.005.npz"
OUT = "--out-dir models/study --results results/study.jsonl"
SEEDS = range(5)
N_DET = 24


def train(model, hidden, teacher=None, tag="", seed=0, extra=""):
    h = " ".join(map(str, hidden))
    t = f" --teacher {teacher}" if teacher else ""
    kd = " --kd 0.5" if model != "fp" else ""
    s = f" --seed {seed}" if seed else ""
    return f"python host/train.py --data {DATA} --model {model} --hidden {h}{t}{kd} {OUT} --tag {tag}{s} {extra}".strip()


def teacher_path(w):
    return f"models/study/fp_d3_r3_p0.005_w{w}.pt"


def main():
    jobs = ["# Main study, p=0.005 (generated by host/make_study.py)", "# teachers"]
    widths_bnn = [128, 192, 256, 384]
    widths_l0 = [32, 64, 96, 128]
    for w in sorted(set(widths_bnn + widths_l0)):
        jobs.append(train("fp", [w, w], tag=f"w{w}"))
    jobs.append("WAIT")

    t128 = teacher_path(128)
    jobs.append("# A: layer-0 saliency sweep (128x128)")
    for seed in SEEDS:
        jobs.append(train("bnn", [128, 128], t128, "w128", seed))
        for k in (2, 3):
            methods = ("awq", "inverse", "wanda", "random") if k == 3 else ("awq", "random")
            for n in (1, 2, 3, 6, 12):
                for m in methods:
                    jobs.append(train("expanded", [128, 128], t128, f"L0n{n}", seed,
                                      f"--k {k} --salient-layers {n / N_DET:.6f} 0 0 --saliency {m}"))
            jobs.append(train("expanded", [128, 128], t128, "L0n24", seed,
                              f"--k {k} --salient-layers 1 0 0 --saliency awq"))

    jobs.append("# B: hidden-layer expansion on top of a 3-bit layer 0")
    for seed in SEEDS:
        for f in (0.1, 0.2):
            for m in ("awq", "random"):
                jobs.append(train("expanded", [128, 128], t128, f"L0all_H{int(f * 100)}", seed,
                                  f"--k 3 --salient-layers 1 {f} {f} --saliency {m}"))

    jobs.append("# C: Pareto -- plain BNN widths vs layer-0 3-bit BNN widths")
    for seed in SEEDS:
        for w in widths_bnn:
            if w != 128:
                jobs.append(train("bnn", [w, w], teacher_path(w), f"w{w}", seed))
        for w in widths_l0:
            if w != 128:
                jobs.append(train("expanded", [w, w], teacher_path(w), f"w{w}_L0n24", seed,
                                  "--k 3 --salient-layers 1 0 0 --saliency awq"))

    Path("jobs").mkdir(exist_ok=True)
    Path("jobs/study.txt").write_text("\n".join(jobs) + "\n")
    print(f"wrote jobs/study.txt: {sum(1 for j in jobs if j.startswith('python'))} jobs")


if __name__ == "__main__":
    main()
